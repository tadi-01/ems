import mongoose from "mongoose";
import assert from "node:assert/strict";
import Payroll from "../models/Payroll.js";
import BudgetRequest from "../models/BudgetRequest.js";
import { getMonthText } from "../utils/dateHelpers.js";
import { prepareScheduledPayroll } from "../utils/payrollScheduler.js";

// Tests financial boundaries against real transactions in the isolated integration database.
async function verifyWorkflow(request, data) {
  const { admin, adminToken, employee, details, employeeLogin, token, reviewerToken, department } = data;
  const month = getMonthText();
  const restricted = await request("/employees", "GET", undefined, token);
  assert.equal(restricted[0].salary, undefined);
  await request("/settings", "GET", undefined, token, 403);
  await request("/budgets", "GET", undefined, token, 403);
  await request(`/users/${employeeLogin.user.id}/role`, "PUT", { role: "HR" }, adminToken);
  await request(`/budgets/departments/${department._id}`, "PUT", { budget: 1200, month, reason: "QA monthly limit" }, token, 403);
  await request(`/departments/${department._id}`, "PUT", { name: department.name, manager: admin._id, budget: 1 }, adminToken, 400);
  await request(`/budgets/departments/${department._id}`, "PUT", { budget: 1200, month, reason: "QA monthly limit" }, adminToken);
  const results = await Promise.all([1, 2].map((n) => request("/budgets/expenses", "POST", { department: department._id, month, amount: 150, reason: `Concurrent expense ${n}` }, token, 201)));
  assert.deepEqual(results.map((item) => item.status).sort(), ["Approved", "Pending approval"]);
  let usage = await request(`/budgets?month=${month}`, "GET", undefined, adminToken);
  assert.equal(usage.rows[0].committed, 1150);
  const pendingExpense = results.find((item) => item.status === "Pending approval");
  await request(`/budgets/requests/${pendingExpense._id}`, "PUT", { decision: "Approved", confirmed: true, reason: "Over limit" }, adminToken, 400);
  const hire = await request("/employees", "POST", { ...details, user: "", employeeId: "QA002", email: "hire@example.test", salary: 500 }, token, 202);
  assert.equal(hire.pendingApproval, true);
  const change = await request(`/employees/${employee._id}`, "PUT", { ...details, salary: 1500 }, token, 202);
  assert.equal(change.pendingApproval, true);
  await request(`/budgets/departments/${department._id}`, "PUT", { budget: 2200, month, reason: "Authorize staffing" }, adminToken);
  await request(`/budgets/requests/${hire.request._id}`, "PUT", { decision: "Approved", confirmed: true, reason: "Hire authorized" }, adminToken);
  await request(`/budgets/requests/${change.request._id}`, "PUT", { decision: "Approved", confirmed: true, reason: "Salary authorized" }, adminToken);
  usage = await request(`/budgets?month=${month}`, "GET", undefined, adminToken);
  assert.equal(usage.rows[0].committed, 2150);
  const second = await request("/departments", "POST", { name: "QA Source", manager: admin._id, budget: 1000, reason: "Unallocated reserve" }, adminToken, 201);
  await request(`/budgets/departments/${department._id}`, "PUT", { budget: 2400, fromDepartment: second._id, month, reason: "Reallocate 200" }, adminToken);
  const rows = (await request(`/budgets?month=${month}`, "GET", undefined, adminToken)).rows;
  assert.equal(rows.find((row) => row.department._id === second._id).budget, 800);
  const slip = await request("/payroll", "POST", { employee: employee._id, month: "2027-04", basicSalary: 1500, overtime: 100, allowances: 50, pension: 30, loanDeductions: 20, tax: 100 }, token, 201);
  assert.equal(slip.netSalary, 1500);
  await request(`/payroll/${slip._id}/decision`, "PUT", { decision: "Approved", confirmed: true, reason: "Checked", revision: slip.revision }, token, 403);
  await request(`/payroll/${slip._id}/decision`, "PUT", { decision: "Approved", confirmed: true, reason: "Checked", revision: 99 }, adminToken, 400);
  await request(`/payroll/${slip._id}/decision`, "PUT", { decision: "Approved", confirmed: true, reason: "Checked", revision: slip.revision }, adminToken);
  await request(`/payroll/${slip._id}`, "PUT", { tax: 0 }, token, 400);
  await request(`/payroll/${slip._id}`, "DELETE", undefined, token, 400);
  const over = await request("/payroll", "POST", { employee: employee._id, month: "2027-05", basicSalary: 5000 }, token, 201);
  assert.equal(over.budgetExceeded, true);
  await request(`/payroll/${over._id}/decision`, "PUT", { decision: "Approved", confirmed: true, reason: "Must remain pending", revision: over.revision }, adminToken, 400);
  await request(`/payroll/${over._id}/decision`, "PUT", { decision: "Rejected", confirmed: true, reason: "Return for correction", revision: over.revision }, adminToken);
  const legacy = await Payroll.collection.insertOne({ employee: new mongoose.Types.ObjectId(employee._id), month: "2025-01", basicSalary: 1000, allowances: 0, bonuses: 0, tax: 0, deductions: 0, netSalary: 1000, createdBy: admin._id });
  await request(`/payroll/${legacy.insertedId}`, "PUT", { tax: 50 }, token, 400);
  assert.ok((await request("/payroll/me", "GET", undefined, token)).some((item) => item.month === "2025-01"));
  await request("/settings", "PUT", { preparationDay: 1, approvalDay: 28, automaticPreparation: true, reason: "QA scheduler" }, adminToken);
  await prepareScheduledPayroll(); await prepareScheduledPayroll();
  assert.equal(await Payroll.countDocuments({ employee: employee._id, month }), 1);
  const scheduled = await Payroll.findOne({ employee: employee._id, month }).lean();
  assert.equal(scheduled.requiresReview, true);
  await request(`/payroll/${scheduled._id}/decision`, "PUT", { decision: "Approved", confirmed: true, reason: "Not yet reviewed", revision: 0 }, adminToken, 400);
  const reviewed = await request(`/payroll/${scheduled._id}`, "PUT", { tax: 100, pension: 30 }, token);
  await request(`/payroll/${scheduled._id}/decision`, "PUT", { decision: "Approved", confirmed: true, reason: "HR reviewed amounts", revision: reviewed.revision }, adminToken);
  await request("/settings", "PUT", { automaticPreparation: false, preparationDay: 25, reason: "End QA scheduling" }, adminToken);
  const notifications = await request("/workflow/notifications", "GET", undefined, adminToken);
  assert.ok(notifications.unread > 0);
  await request(`/workflow/notifications/${notifications.items[0]._id}/read`, "PUT", {}, token, 404);
  await request(`/workflow/notifications/${notifications.items[0]._id}/read`, "PUT", {}, adminToken);
  const events = await request("/workflow/audit", "GET", undefined, adminToken);
  assert.ok(events.some((event) => event.action === "payroll.approved"));
  assert.ok(events.some((event) => event.action === "budget.adjust"));
  assert.equal((await BudgetRequest.findById(hire.request._id)).status, "Approved");
  console.log("Workflow checks passed: concurrent spending, pending hires/salary changes, reallocation, approval, legacy records, scheduler, notifications and audit.");
}
export default verifyWorkflow;
